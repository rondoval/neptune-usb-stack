#!/usr/bin/env python3
"""gen_camddriver.py - turn the linked CAMD MIDI driver (a HUNK exe) into CAMDDriver.c.

The camdusbmidi class embeds the driver as a `ULONG[]` and writes it to DEVS:Midi/<id>
at bind time, patching the driver's name[] to the id (camd matches the name against the
file name). This replaces the frozen 2006 blob with the freshly built driver and co-emits
the name-string offset (which moves whenever the driver is recompiled), the size of the
name[] array (the room the class may patch) and the offset of MidiDeviceData.NPorts (the
class patches the device's cable count there - camd reads NPorts from the table before it
calls Init, so the driver cannot set it at run time), so the class never hardcodes any of them.

Usage: gen_camddriver.py <driver-binary> <out-CAMDDriver.c>
"""
import sys, struct

HUNK_CODE = b'\x00\x00\x03\xe9'
STUB_MAGIC = b'\x70\xff\x4e\x75\x4d\x44\x45\x56'  # `moveq #-1,d0; rts` + 'MDEV'
NAME = b'camdusbmidi'
# Match the NUL terminator too: the driver's $VER cookie and the "camdusbmidi.usbclass" it opens
# also spell the name, so a bare substring search can land on those instead of name[].
NAME_Z = NAME + b'\x00'
NAME_SIZE = 32   # sizeof(name[]) in camd_driver.c; the class strcpy()s ids of up to 31 chars
NPORTS_MAX = 16  # CAMD_MAX_PORTS: the NPorts the table carries, the class patches the real count

def main():
    src, dst = sys.argv[1], sys.argv[2]
    data = open(src, 'rb').read()
    if len(data) % 4:
        data += b'\x00' * (4 - len(data) % 4)

    # Layout guarantee: the first code hunk's body must begin with the do-not-execute
    # stub immediately followed by MidiDeviceData's MDD_Magic ('MDEV') - i.e. camd.library
    # finds the table at offset 4 of the loaded image. (8 = HUNK_CODE marker + size long.)
    hc = data.find(HUNK_CODE)
    if hc < 0:
        sys.exit("gen_camddriver: no HUNK_CODE in %s" % src)
    body = data[hc + 8:hc + 16]
    if body != STUB_MAGIC:
        sys.exit("gen_camddriver: CAMD layout broken - first code hunk must start with "
                 "`moveq #-1,d0; rts` + 'MDEV', got %r" % body)
    # MidiDeviceData.NPorts: struct offset 32 (Magic 4, Name 4, IDString 4, Version/Revision
    # 2+2, Init/Expunge/OpenPort/ClosePort 4 each), Flags right behind it. The table's values
    # (CAMD_MAX_PORTS, Flags 1) pin the layout; a drift fails the build.
    nports_off = hc + 8 + 4 + 32
    if data[nports_off] != NPORTS_MAX or data[nports_off + 1] != 1:
        sys.exit("gen_camddriver: MidiDeviceData layout broken - expected NPorts %d, Flags 1 at "
                 "0x%x, got %d, %d" % (NPORTS_MAX, nports_off, data[nports_off], data[nports_off + 1]))

    # Name string offset (the class strcpy()s the per-unit id over it). Must be unique:
    # patching the wrong occurrence would corrupt the driver silently.
    off = data.find(NAME_Z)
    if off < 0:
        sys.exit("gen_camddriver: name string %r not found" % NAME_Z)
    if data.find(NAME_Z, off + 1) >= 0:
        sys.exit("gen_camddriver: name string %r occurs more than once - cannot tell "
                 "name[] from a copy" % NAME_Z)
    # The class overwrites NAME_SIZE bytes here: they must all belong to name[] (the
    # initializer's padding is zero), or a long id would clobber whatever follows.
    tail = data[off + len(NAME_Z):off + NAME_SIZE]
    if len(tail) != NAME_SIZE - len(NAME_Z) or tail.strip(b'\x00'):
        sys.exit("gen_camddriver: name[] is not %d zero-padded bytes at 0x%x - keep "
                 "`char name[%d]` in camd_driver.c" % (NAME_SIZE, off, NAME_SIZE))

    words = struct.unpack('>%dL' % (len(data) // 4), data)
    with open(dst, 'w') as f:
        f.write("/* AUTO-GENERATED by camd/gen_camddriver.py from camd/camd_driver.c - do not edit. */\n")
        f.write("/* The embedded CAMD MIDI driver (a HUNK exe); the class writes it to\n")
        f.write(" * DEVS:Midi/<id> at bind time and patches the name at CAMDDriver_NAMEOFFSET. */\n")
        f.write("static const ULONG CAMDDriver[] = {\n")
        for i in range(0, len(words), 8):
            f.write("    " + " ".join("0x%08X," % w for w in words[i:i + 8]) + "\n")
        f.write("};\n")
        f.write('#define CAMDDriver_NAMEOFFSET 0x%X  /* byte offset of name[]="camdusbmidi" */\n' % off)
        f.write('#define CAMDDriver_NAMESIZE %d      /* sizeof(name[]): the room the class may patch */\n' % NAME_SIZE)
        f.write('#define CAMDDriver_NPORTSOFFSET 0x%X  /* byte offset of MidiDeviceData.NPorts */\n' % nports_off)

if __name__ == '__main__':
    main()
